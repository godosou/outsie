func check(_ name: String, _ got: String, _ want: String, _ failures: inout Int) {
    if got == want {
        print("  ok   \(name)")
    } else {
        print("  FAIL \(name)\n       got  \(got)\n       want \(want)")
        failures += 1
    }
}

func selfTest() -> Int32 {
    var f = 0
    let pkM = hexDecode(Vec.pkM)!, pkP = hexDecode(Vec.pkP)!
    let nm = hexDecode(Vec.nm)!, np = hexDecode(Vec.np)!

    check("commitment", hex(commitment(pkM: pkM, pkP: pkP, np: np)), Vec.commit, &f)

    let sh = sasHash(pkM: pkM, pkP: pkP, nm: nm, np: np)
    check("transcript hash", hex(sh), Vec.sasHash, &f)
    check("six digits", sasDigits(sh), Vec.digits, &f)

    // Both directions of the ECDH must land on the same X, or the two sides
    // derive different keys and the only symptom is a phone that never verifies.
    do {
        let xm = try ecdhX(privateScalar: hexDecode(Vec.skM)!, peerPublic: pkP)
        let xp = try ecdhX(privateScalar: hexDecode(Vec.skP)!, peerPublic: pkM)
        check("ECDH x (mac side)", hex(xm), Vec.ecdhX, &f)
        check("ECDH x (phone side)", hex(xp), Vec.ecdhX, &f)
        check("derived key", hex(deriveKey(ecdhX: xm, salt: sh)), Vec.key, &f)
    } catch {
        print("  FAIL ECDH threw: \(error)")
        f += 1
    }

    // A commitment that does not match its nonce must be refused. This is the
    // step a man in the middle has to beat, so it gets its own check rather than
    // being implied by the happy path.
    var tampered = np
    tampered[tampered.startIndex] ^= 0x01
    if hex(commitment(pkM: pkM, pkP: pkP, np: tampered)) == Vec.commit {
        print("  FAIL a different nonce produced the same commitment")
        f += 1
    } else {
        print("  ok   a different nonce breaks the commitment")
    }

    // Changing either public key must change the digits, or the SAS is not
    // actually binding the keys it is supposed to authenticate.
    var otherKey = pkM
    otherKey[otherKey.startIndex + 1] ^= 0x01
    let shifted = sasHash(pkM: otherKey, pkP: pkP, nm: nm, np: np)
    if sasDigits(shifted) == Vec.digits {
        print("  FAIL a substituted public key produced the same digits")
        f += 1
    } else {
        print("  ok   a substituted public key changes the digits")
    }

    // Garbage peer keys are refused rather than parsed.
    for bad in ["", "04", String(repeating: "00", count: 65)] {
        if parsePeerKey(hexDecode(bad) ?? Data()) != nil {
            print("  FAIL accepted a malformed peer key: \(bad.prefix(8))")
            f += 1
        }
    }
    print("  ok   malformed peer keys are refused")

    print(f == 0 ? "\nself-test passed" : "\n\(f) failed")
    return f == 0 ? 0 : 1
}

// MARK: - main

let args = Array(CommandLine.arguments.dropFirst())
if args.first == "--self-test" {
    exit(selfTest())
}
FileHandle.standardError.write("usage: pair-crypto --self-test\n".data(using: .utf8)!)
exit(64)
