// repose-pair-v2 — the Mac side's arithmetic.
//
// Protocol: docs/plans/2026-09-11-pairing-v2.md
//
//   M1  Mac  -> phone : PK_M(65)
//   P1  phone-> Mac   : PK_P(65) ‖ Cp(32)      Cp = SHA256(COMMIT‖PK_M‖PK_P‖Np)
//   M2  Mac  -> phone : Nm(16)
//   P2  phone-> Mac   : Np(16)                 Mac verifies Cp here
//
//   sasHash = SHA256(SAS‖PK_M‖PK_P‖Nm‖Np)
//   digits  = int_be(sasHash[0..4]) mod 1e6
//   K       = HKDF(salt: sasHash, ikm: ECDH_x, info: KDF, 32)
//
// The commitment is the whole protocol. The phone fixes Np before it can see
// Nm, so a man in the middle cannot pick his own nonce after seeing the other
// side's to make both screens agree. Cp covers PK_M as well, so one commitment
// cannot be replayed at a different Mac.
//
// Using sasHash as the HKDF salt means that even on the ~1-in-a-million chance
// the six digits collide, the two halves of a MITM derive different keys and the
// relay still does not join up.
//
// Build: swiftc -O -o pair-crypto pair-crypto.swift
// Run:   ./pair-crypto --self-test

import CryptoKit
import Foundation

let COMMIT_LABEL = "repose-pair-v2 commit"
let SAS_LABEL = "repose-pair-v2 sas"
let KDF_LABEL = "repose-pair-v2 presence-key"

func hexDecode(_ s: String) -> Data? {
    guard s.count % 2 == 0, !s.isEmpty else { return nil }
    var out = Data(capacity: s.count / 2)
    var i = s.startIndex
    while i < s.endIndex {
        let j = s.index(i, offsetBy: 2)
        guard let b = UInt8(s[i..<j], radix: 16) else { return nil }
        out.append(b)
        i = j
    }
    return out
}

func hex(_ d: Data) -> String { d.map { String(format: "%02x", $0) }.joined() }

func ascii(_ s: String) -> Data { Data(s.utf8) }

// MARK: - the four values everything else is built from

func commitment(pkM: Data, pkP: Data, np: Data) -> Data {
    Data(SHA256.hash(data: ascii(COMMIT_LABEL) + pkM + pkP + np))
}

func sasHash(pkM: Data, pkP: Data, nm: Data, np: Data) -> Data {
    Data(SHA256.hash(data: ascii(SAS_LABEL) + pkM + pkP + nm + np))
}

/// Six digits, zero padded. Short on purpose: a human has to read it off two
/// screens and compare, and a longer string gets compared less carefully.
func sasDigits(_ hash: Data) -> String {
    let first4 = hash.prefix(4)
    let n = first4.reduce(UInt32(0)) { ($0 << 8) | UInt32($1) }
    return String(format: "%06d", n % 1_000_000)
}

/// HKDF-SHA256, salted with the transcript hash.
func deriveKey(ecdhX: Data, salt: Data) -> Data {
    let prk = HMAC<SHA256>.authenticationCode(for: ecdhX, using: SymmetricKey(data: salt))
    let okm = HMAC<SHA256>.authenticationCode(
        for: ascii(KDF_LABEL) + Data([0x01]),
        using: SymmetricKey(data: Data(prk)))
    return Data(okm)
}

/// The X coordinate of the shared point, 32 bytes with leading zeros kept.
///
/// CryptoKit's sharedSecretFromKeyAgreement is exactly that, which is the
/// definition the other side has to match -- a shared secret trimmed to its
/// significant bytes would agree with OpenSSL only when X happens not to start
/// with a zero, i.e. 255 times out of 256.
func ecdhX(privateScalar: Data, peerPublic: Data) throws -> Data {
    let sk = try P256.KeyAgreement.PrivateKey(rawRepresentation: privateScalar)
    let pk = try P256.KeyAgreement.PublicKey(x963Representation: peerPublic)
    let shared = try sk.sharedSecretFromKeyAgreement(with: pk)
    return shared.withUnsafeBytes { Data($0) }
}

/// Reject a peer key before touching it. CryptoKit's x963 initializer already
/// refuses points that are not on the curve, and refusing loudly here keeps that
/// from looking like a transport error later.
func parsePeerKey(_ d: Data) -> Data? {
    guard d.count == 65, d.first == 0x04 else { return nil }
    return (try? P256.KeyAgreement.PublicKey(x963Representation: d)) != nil ? d : nil
}

